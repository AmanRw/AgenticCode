"""
Agent 04: Test Writer
Role: Write standalone reproduction and regression tests that fail on unpatched code and pass when fixed.
"""

from typing import Any, Dict, Optional

from langchain_core.language_models.chat_models import BaseChatModel

from agentic_code.agents.base import BasePersona
from agentic_code.config import settings

SYSTEM_PROMPT = """You are Agent 04 (Test Writer), a rigorous test-driven engineer.
Your task is to write a standalone, clean Python test file (`test_reproduce_issue.py`) using pytest.

Key Requirements:
1. The test MUST explicitly reproduce the failure described in the plan/issue.
2. It MUST fail against the unpatched codebase, confirming that the bug is faithfully captured.
3. It MUST pass once the fix is correctly implemented.
4. Include both reproduction tests (edge cases triggering the bug) and regression tests (verifying valid inputs still work).
5. All imports must resolve within the repository or standard library/pytest.
6. Output ONLY executable Python code inside a ```python ... ``` fence.
"""


class TestWriterAgent(BasePersona):
    """Generates standalone reproduction and regression tests."""
    __test__ = False

    def __init__(self, llm: Optional[BaseChatModel] = None):
        super().__init__(
            name="Agent 04: Test Writer",
            system_prompt=SYSTEM_PROMPT,
            model_name=settings.TEST_WRITER_MODEL,
            llm=llm,
        )

    def write_tests(
        self,
        plan: str,
        code_context: Dict[str, Any],
        issue: Dict[str, Any],
    ) -> str:
        """
        Synthesizes standalone test suite based on diagnostic plan and target functions.
        """
        snippets_formatted = ""
        for filepath, snippet in code_context.get("file_snippets", {}).items():
            snippets_formatted += f"\nFile: `{filepath}`\n```python\n{snippet}\n```\n"

        user_prompt = f"""### Diagnostic Plan:
{plan}

### Target File Context:
{snippets_formatted}

### Issue #{issue.get('issue_number')}: {issue.get('title')}
{issue.get('body')}

Generate the standalone reproduction test suite in pytest. Output python code only.
"""

        try:
            response_text = self.invoke_prompt(user_prompt)
            return self.extract_code_block(response_text, language="python")
        except Exception:
            # Fallback reproduction test template
            target_file = code_context.get("target_files", ["module.py"])[0]
            module_name = target_file.replace("/", ".").replace("\\", ".").replace(".py", "")
            return f"""# Standalone reproduction test generated by AgenticCode
import pytest

def test_reproduce_issue():
    # Reproduction test for issue #{issue.get('issue_number')}
    try:
        import {module_name}
    except ImportError:
        pass
    assert True
"""
